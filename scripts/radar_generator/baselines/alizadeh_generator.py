#!/usr/bin/env python3
"""Alizadeh-inspired radar heart-rate feature exporter for ICR-DS.

Run after placing the ICR-DS root path in DATA_ROOT below:
    python alizadeh_generator.py

Input for each subject:
    sub-XXX/raw/radar/adc_data_N.bin (or adc_data_Raw_N.bin)
    sub-XXX/processed/sXXX_session.h5 (completed, aligned session)

Output (new file; inputs are never modified):
    sub-XXX/processed/sXXX_alizadeh.h5

Processing summary:
    * One fixed TX/RX chirp per frame; 3 TX, 4 RX, 96 ADC samples,
      255 loops per TX; the TDM chirp order is assumed to be tx + 3*loop.
    * Hann-windowed 96-point range FFT, candidate bins 3--15.
    * 36-second windows with an 18-second hop at 11.11 frames/s.
    * MTI-energy range selection, algebraic least-squares IQ circle correction,
      phase unwrapping and slow-time vibration FFT for heart-rate estimation.
    * Heart-rate peak search: 0.8--2.0 Hz, with three-bin log-Gaussian
      interpolation. Failed circle fits fall back to the uncorrected signal
      and are explicitly flagged.

This is an ICR-DS adaptation of Alizadeh et al. (IEEE Access, 2019),
not an exact reproduction of their radar acquisition or recording protocol.

The output stores per-window range I/Q, corrected/uncorrected phase, range
selection, circle-fit diagnostics, spectra, heart-rate estimates and timing.
If physiology is present in the source session, a relative HDF5 external link
is included; labels are not generated by this exporter.

Dependencies: numpy, h5py.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
import os
from pathlib import Path
import re
import warnings

import h5py
import numpy as np

NUM_TX = 3
NUM_RX = 4
ADC_SAMPLES = 96
LOOPS_PER_TX = 255
SOURCE_BLOCK_FRAMES = 200
WINDOW_FRAMES = 400
STRIDE_FRAMES = 200
FRAME_PERIOD_S = 0.09

# Set this to the directory containing sub-XXX folders.
DATA_ROOT = Path("path/to/ICR-DS")

# Fixed processing configuration used for the ICR-DS experiments.
TX_INDEX = 0
RX_INDEX = 0
CHIRP_LOOP = 0
FFT_SIZE = ADC_SAMPLES
RANGE_START = 3
RANGE_STOP = 15
RANGE_METHOD = "mti-energy"
RANGE_LOW_HZ = 0.1
RANGE_HIGH_HZ = 2.0
HEART_LOW_HZ = 0.8
HEART_HIGH_HZ = 2.0
VIBRATION_HANN = False

BIN_RE = re.compile(r"adc_data_(?:Raw_)?(\d+)\.bin$", re.IGNORECASE)
SUBJECT_RE = re.compile(r"sub-(\d+)$", re.IGNORECASE)
SESSION_RE = re.compile(r"s(\d+)_session\.h5$", re.IGNORECASE)


def ordered_bin_files(folder: Path) -> list[Path]:
    matches = []
    for path in Path(folder).glob("*.bin"):
        m = BIN_RE.fullmatch(path.name)
        if m:
            matches.append((int(m.group(1)), path))
    if not matches:
        raise FileNotFoundError(f"No adc_data_N.bin or adc_data_Raw_N.bin files in {folder}")
    matches.sort(key=lambda p: p[0])
    numbers = [n for n, _ in matches]
    if len(set(numbers)) != len(numbers):
        raise ValueError("Duplicate numerical raw file indices (e.g., Raw_0 and 0); ambiguous")
    if any(b != a+1 for a, b in zip(numbers, numbers[1:])):
        warnings.warn("Numbered raw files have gaps. Assuming continuous acquisition may be unsafe")
    return [p for _, p in matches]


def frames_per_file(path: Path, loops_per_tx: int) -> int:
    bytes_per_frame = NUM_TX * NUM_RX * loops_per_tx * ADC_SAMPLES * 2 * 2
    size = path.stat().st_size
    n_frames, tail = divmod(size, bytes_per_frame)
    if n_frames == 0:
        raise ValueError(f"{path.name}: no complete raw frames")
    if tail:
        warnings.warn(f"{path.name}: discarding {tail} trailing bytes, as original reader does")
    return int(n_frames)


def utc(value: object) -> datetime:
    if isinstance(value, bytes):
        value = value.decode("utf-8")
    dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    if dt.tzinfo is None:
        raise ValueError(f"Source metadata time {value!r} has no timezone")
    return dt.astimezone(timezone.utc)


def iso(dt: datetime) -> str:
    return dt.isoformat().replace("+00:00", "Z")


def decode_fixed_chirp(packed_frames: np.ndarray, *, loops_per_tx: int,
                       tx: int, rx: int, chirp_loop: int) -> np.ndarray:
    if not 0 <= tx < NUM_TX or not 0 <= rx < NUM_RX or not 0 <= chirp_loop < loops_per_tx:
        raise ValueError("Invalid tx/rx/chirp_loop index")
    per_chirp = NUM_RX * ADC_SAMPLES * 2
    chirps = packed_frames.reshape(len(packed_frames), NUM_TX*loops_per_tx, per_chirp)
    data = chirps[:, tx+NUM_TX*chirp_loop, :]
    iq = np.empty((len(packed_frames), NUM_RX*ADC_SAMPLES), np.complex64)
    # EXACT original I/Q convention (input is signed int16):
    iq[:, 0::2] = data[:, 0::4].astype(np.float32) + 1j*data[:, 2::4].astype(np.float32)
    iq[:, 1::2] = data[:, 1::4].astype(np.float32) + 1j*data[:, 3::4].astype(np.float32)
    return iq.reshape(len(packed_frames), NUM_RX, ADC_SAMPLES)[:, rx, :]


def iter_range_blocks(files: list[Path], per_file_counts: list[int], *,
                      start_frame: int, frames_to_keep: int, loops_per_tx: int,
                      tx: int, rx: int, chirp_loop: int, fft_size: int,
                      range_bins: np.ndarray, chunk_frames: int = 16):
    """Read selected raw frames across file edges without losing window alignment."""
    frame_words = NUM_TX*NUM_RX*loops_per_tx*ADC_SAMPLES*2
    hann = np.hanning(ADC_SAMPLES).astype(np.float32)
    current_global_frame = 0
    stop_frame = start_frame + frames_to_keep
    temp = np.empty((WINDOW_FRAMES, len(range_bins)), np.complex64)
    filled = 0
    sent = 0
    for file_path, file_n in zip(files, per_file_counts):
        file_start, file_end = current_global_frame, current_global_frame + file_n
        current_global_frame = file_end
        begin = max(start_frame, file_start)
        end = min(stop_frame, file_end)
        if begin >= end:
            continue
        mem = np.memmap(file_path, mode="r", dtype="<i2", shape=(file_n,frame_words))
        local_begin = begin - file_start
        local_end = end - file_start
        for i in range(local_begin, local_end, chunk_frames):
            j = min(i+chunk_frames, local_end)
            adc = decode_fixed_chirp(mem[i:j], loops_per_tx=loops_per_tx,
                                     tx=tx, rx=rx, chirp_loop=chirp_loop)
            spectrum = np.fft.fft(adc*hann[None, :], n=fft_size, axis=-1)
            selected = np.asarray(spectrum[:,range_bins], dtype=np.complex64)
            pos = 0
            while pos < len(selected):
                n = min(WINDOW_FRAMES-filled, len(selected)-pos)
                temp[filled:filled+n] = selected[pos:pos+n]
                filled += n
                pos += n
                if filled == WINDOW_FRAMES:
                    yield temp.copy()
                    temp[:WINDOW_FRAMES-STRIDE_FRAMES] = temp[STRIDE_FRAMES:]
                    filled = WINDOW_FRAMES-STRIDE_FRAMES
                    sent += 1
        del mem
    if sent != frames_to_keep // STRIDE_FRAMES - 1 or filled != STRIDE_FRAMES:
        raise RuntimeError("Raw frame alignment differs from expected sliding 400-frame windows")


def alizadeh_circle_fit(iq: np.ndarray, *, max_condition: float = 1e6,
                        min_coverage_degrees: float = 40.0,
                        max_normalized_radial_error: float = 0.60):
    """Alizadeh Appendix A algebraic LS fit, with documented reliability gate.

    The literal algebra is A=[1,-2I,-2Q], b=-(I²+Q²), y=[R,cI,cQ].
    We centre and SCALE the complex samples before lstsq for numerical
    conditioning. This represents the SAME algebraic LS circle, translated
    and rescaled; the resulting centre is transformed back to original units.

    Returns (corrected_complex, [cI,cQ], radius, condition, relative_radial_RMSE,
             coverage_degrees, valid). If invalid: corrected == ORIGINAL iq.
    """
    z = np.asarray(iq, dtype=np.complex128).reshape(-1)
    nan_center = np.array([np.nan, np.nan], np.float32)
    if len(z) < 3 or not np.all(np.isfinite(z)):
        return z.copy(), nan_center, np.nan, np.inf, np.inf, 0.0, False
    origin = z.mean()
    scale = float(np.sqrt(np.mean(np.abs(z-origin)**2)))
    if not np.isfinite(scale) or scale < 1e-12:
        return z.copy(), nan_center, np.nan, np.inf, np.inf, 0.0, False
    w = (z-origin)/scale
    I, Q = w.real, w.imag
    A = np.column_stack((np.ones(len(z)), -2*I, -2*Q))
    b = -(I*I+Q*Q)
    coefficients, _, rank, singular_values = np.linalg.lstsq(A, b, rcond=None)
    if rank < 3 or singular_values[-1] <= 0:
        return z.copy(), nan_center, np.nan, np.inf, np.inf, 0.0, False
    condition = float(singular_values[0]/singular_values[-1])
    R, cx, cy = coefficients
    rad2 = float(cx*cx+cy*cy-R)
    if not np.isfinite(rad2) or rad2 <= 0:
        return z.copy(), nan_center, np.nan, condition, np.inf, 0.0, False
    centre = origin + scale*(cx+1j*cy)
    radius = scale*np.sqrt(rad2)
    radial_dist = np.abs(z-centre)
    rel_error = float(np.sqrt(np.mean((radial_dist-radius)**2))/radius)
    angles = np.sort(np.mod(np.angle(z-centre), 2*np.pi))
    gaps = np.diff(np.r_[angles, angles[0]+2*np.pi])
    coverage = float(np.rad2deg(2*np.pi-np.max(gaps)))
    valid = bool(np.isfinite(condition) and condition<=max_condition
                 and np.isfinite(rel_error) and rel_error <= max_normalized_radial_error
                 and coverage >= min_coverage_degrees)
    center_xy = np.asarray([centre.real, centre.imag], np.float32)
    return (z-centre if valid else z.copy()), center_xy, float(radius), condition, rel_error, coverage, valid


def vibration_fft(phase: np.ndarray, *, window: np.ndarray) -> np.ndarray:
    """Spectral magnitude across 400 slow-time phase samples (NOT chirp-Doppler)."""
    x = np.asarray(phase, dtype=np.float64)
    if x.shape != (WINDOW_FRAMES,) or not np.all(np.isfinite(x)):
        return np.zeros(WINDOW_FRAMES//2+1, np.float32)
    return np.abs(np.fft.rfft((x-x.mean())*window)).astype(np.float32)


def gaussian_peak_frequency(spectrum: np.ndarray, sample_hz: float,
                            heart_low_hz: float, heart_high_hz: float) -> float:
    """Largest heart-band spectral peak + three-point log-Gaussian interpolation."""
    magnitude = np.asarray(spectrum, dtype=np.float64)
    bin_width = sample_hz / WINDOW_FRAMES
    frequencies = np.arange(len(magnitude))*bin_width
    candidates = np.flatnonzero((frequencies >= heart_low_hz)
                                & (frequencies <= heart_high_hz)
                                & (np.arange(len(magnitude)) > 0)
                                & (np.arange(len(magnitude)) < len(magnitude)-1))
    if candidates.size == 0:
        raise ValueError("HR search band must include at least one non-edge FFT bin")
    peak_index = int(candidates[np.argmax(magnitude[candidates])])
    if not np.isfinite(magnitude[peak_index]) or magnitude[peak_index] <= 1e-12:
        return float("nan")
    # Gaussian log-peak interpolation (three contiguous frequency bins).
    tiny = np.finfo(float).tiny
    left, middle, right = np.log(np.maximum(magnitude[peak_index-1:peak_index+2], tiny))
    denominator = left - 2*middle + right
    if abs(denominator) < 1e-12 or denominator >= 0:
        offset = 0.0
    else:
        offset = float(np.clip(0.5*(left-right)/denominator, -0.5, 0.5))
    estimate = (peak_index+offset)*bin_width
    return float(np.clip(estimate, heart_low_hz, heart_high_hz))


def inspect_alignment(existing_h5: Path, bin_folder: Path, *,
                      loops_per_tx: int = LOOPS_PER_TX) -> dict:
    """Audit original aligned HDF5 block length and raw per-file truncation."""
    if not existing_h5.is_file():
        raise FileNotFoundError(existing_h5)
    files = ordered_bin_files(bin_folder)
    counts = [frames_per_file(p, loops_per_tx) for p in files]
    total_frames = sum(counts)
    raw_blocks, tail = divmod(total_frames, SOURCE_BLOCK_FRAMES)
    with h5py.File(existing_h5, "r") as f:
        if "raw/radar/beamformed_cube" not in f:
            raise KeyError("Source HDF5 missing raw/radar/beamformed_cube")
        old = f["raw/radar/beamformed_cube"]
        if old.ndim<2 or old.shape[1] != SOURCE_BLOCK_FRAMES:
            raise ValueError("Source radar is not stored as 200-frame windows")
        retained = int(old.shape[0])
        if retained < 1 or retained > raw_blocks:
            raise ValueError("Raw file frames cannot account for retained source windows")
        if "raw/radar/localization_cube" in f and f["raw/radar/localization_cube"].shape[0] != retained:
            raise ValueError("Source beamformed/localization window counts disagree")
        start_dt = utc(f.attrs["start_time_iso"])
        end_dt = utc(f.attrs["end_time_iso"])
        # The source session stores an inclusive end one second before the
        # exclusive boundary of the final 18-second block.
        actual = (end_dt-start_dt).total_seconds()+1.0
        expected = retained * SOURCE_BLOCK_FRAMES * FRAME_PERIOD_S
        if abs(actual-expected) > 0.1:
            raise ValueError(f"Aligned metadata time span {actual:.3f}s disagrees with {expected:.3f}s "
                             "from retained 18s blocks; cannot deduce raw offset safely")
        has_physio = "raw/physiology" in f
    start_trim_blocks = raw_blocks-retained
    return dict(files=files, counts=counts, total_frames=total_frames,
                raw_blocks=raw_blocks, end_tail=tail, retained=retained,
                start_trim_blocks=start_trim_blocks,
                start_frame=start_trim_blocks*SOURCE_BLOCK_FRAMES,
                start_dt=start_dt, end_dt=end_dt, has_physio=has_physio)


def export_alizadeh(existing_h5: Path, bin_folder: Path, output_h5: Path, *,
                    tx: int = 0, rx: int = 0, chirp_loop: int = 0,
                    loops_per_tx: int = LOOPS_PER_TX,
                    fft_size: int = ADC_SAMPLES,
                    range_start: int = 3, range_stop: int = 15,
                    frame_period_s: float = FRAME_PERIOD_S,
                    range_method: str = "mti-energy",
                    range_low_hz: float = 0.1, range_high_hz: float = 2.0,
                    heart_low_hz: float = 0.8, heart_high_hz: float = 2.0,
                    vibration_hann: bool = False) -> Path:
    old = Path(existing_h5).resolve()
    folder = Path(bin_folder).resolve()
    target = Path(output_h5).resolve()
    if target == old or target.exists():
        raise FileExistsError("Refusing to overwrite an existing file or source HDF5")
    if not folder.is_dir():
        raise NotADirectoryError(folder)
    if fft_size<ADC_SAMPLES or not 0<=range_start<=range_stop<fft_size//2:
        raise ValueError("Need FFT size >=96 and valid nonnegative candidate range bins")
    if not 0<=tx<NUM_TX or not 0<=rx<NUM_RX or not 0<=chirp_loop<loops_per_tx:
        raise ValueError("TX must 0..2, RX 0..3, chirp loop 0..loops_per_tx-1")
    if abs(SOURCE_BLOCK_FRAMES*frame_period_s-18.0)>1e-8:
        raise ValueError("Frame period must remain 0.09 s for original 18s blocks")
    nyquist = 0.5/frame_period_s
    if not 0<range_low_hz<range_high_hz<nyquist:
        raise ValueError("Invalid range vibration band")
    if not 0<heart_low_hz<heart_high_hz<nyquist:
        raise ValueError("Invalid heart-rate spectral search band")
    if range_method not in ("vibration-energy","mti-energy"):
        raise ValueError("Invalid range selection mode")

    audit=inspect_alignment(old, folder, loops_per_tx=loops_per_tx)
    print(f"Raw complete frames: {audit['total_frames']}; full 18s blocks: {audit['raw_blocks']}")
    print(f"Start trim: {audit['start_trim_blocks']} whole blocks ({audit['start_frame']} frames)")
    print(f"End trim: {audit['end_tail']} full frames + any incomplete per-file frame")
    print(f"Keeping {audit['retained']} aligned blocks from {iso(audit['start_dt'])}")
    print(f"Selection: {range_method}; fixed TX={tx} RX={rx} chirp loop={chirp_loop}")

    range_bins = np.arange(range_start, range_stop+1, dtype=np.int16)
    N=audit['retained']-1
    if N < 1:
        raise ValueError("Need at least two aligned source blocks per 36-second window")
    R=len(range_bins)
    fs=1.0/frame_period_s
    frequencies=np.fft.rfftfreq(WINDOW_FRAMES, d=frame_period_s)
    F=len(frequencies)
    taper = np.hanning(WINDOW_FRAMES) if vibration_hann else np.ones(WINDOW_FRAMES)
    band_mask=(frequencies>=range_low_hz) & (frequencies<=range_high_hz)
    if not np.any(band_mask):
        raise ValueError("Range-vibration band doesn't contain any FFT bins")

    target.parent.mkdir(parents=True, exist_ok=True)
    temp=target.with_name(target.name+".partial")
    if temp.exists():
        raise FileExistsError(f"Stale temporary output exists: {temp}")
    utf8=h5py.string_dtype(encoding="utf-8")

    try:
        with h5py.File(temp, "w") as f:
            f.attrs.update({
                "method":"Alizadeh-inspired vibration-FFT heart-rate estimator (ICR-DS adaptation)",
                "source_session_filename":old.name,
                "raw_bin_file_count":len(audit["files"]),
                "source_alignment_inferred_not_independently_verified":True,
                "aligned_start_time_iso":iso(audit['start_dt']),
                "aligned_end_time_iso_from_source_inclusive":iso(audit['end_dt']),
                "end_time_semantics":"Original source end time is 1 second before exclusive block boundary",
                "frame_period_s_assumed":frame_period_s,
                "slow_time_sampling_rate_hz":fs,
                "frames_per_window":WINDOW_FRAMES,
                "window_duration_s":36.0,
                "window_stride_s":18.0,
                "raw_complete_blocks":audit['raw_blocks'],
                "retained_blocks":audit['retained'],
                "overlapping_windows":N,
                "raw_blocks_trimmed_at_start":audit['start_trim_blocks'],
                "raw_frames_trimmed_at_start":audit['start_frame'],
                "raw_complete_frames_dropped_at_end":audit['end_tail'],
                "num_tx":NUM_TX,"num_rx":NUM_RX,"adc_samples":ADC_SAMPLES,
                "loops_per_tx":loops_per_tx,
                "tx_index_zero_based":tx,"rx_index_zero_based":rx,
                "chirp_loop_index_zero_based":chirp_loop,
                "iq_unpacking":"i0=d[0::4],i1=d[1::4],q0=d[2::4],q1=d[3::4]",
                "chirp_order_assumed":"tx + num_tx*chirp_loop",
                "range_fft_window":"np.hanning(96)",
                "range_fft_size":fft_size,
                "angle_fft_applied":False,
                "chirp_loop_doppler_fft_applied":False,
                "vibration_fft_size":WINDOW_FRAMES,
                "vibration_fft_window":"Hann" if vibration_hann else "rectangular",
                "phase_dc_removed_before_vibration_fft":True,
                "range_selection_method":range_method,
                "range_vibration_band_hz":np.asarray([range_low_hz,range_high_hz]),
                "heart_rate_band_hz":np.asarray([heart_low_hz,heart_high_hz]),
                "circle_fit":"Alizadeh Appendix A algebraic least squares, centred and scaled numerically",
                "circle_fit_thresholds":"condition<=1e6, coverage>=40deg, radial_rmse/radius<=0.6 (our safeguards)",
                "circle_fit_invalid_handling":"return original complex samples; corrected estimate falls back to uncorrected and is flagged",
                "range_selection_uses_ground_truth":False,
                "raw_capture_gaps_assumed_absent":True,
                "labels":"not generated; source_physiology external link only if present",
            })
            f.create_dataset("range_candidate_bins",data=range_bins)
            f.create_dataset("raw_frames_per_file",data=np.asarray(audit['counts'],np.int64))
            if audit['has_physio']:
                f["source_physiology"]=h5py.ExternalLink(os.path.relpath(old,start=target.parent),"/raw/physiology")

            radar=f.create_group("radar")
            model=f.create_group("alizadeh")
            def ds(parent,name,shape,dtype=np.float32):
                kw=dict(compression="lzf",shuffle=True)
                if len(shape)>1:
                    kw["chunks"]=(1,)+shape[1:]
                else:
                    kw["chunks"]=True
                return parent.create_dataset(name, shape=shape,dtype=dtype,**kw)

            iq_ds=ds(radar,"range_iq_36s",(N,WINDOW_FRAMES,R,2))
            un_ph_ds=ds(radar,"phase_uncorrected_36s",(N,WINDOW_FRAMES,R))
            co_ph_ds=ds(radar,"phase_corrected_36s",(N,WINDOW_FRAMES,R))
            selected_range=ds(radar,"selected_range_bin",(N,),np.int16)
            chosen_un=ds(radar,"selected_phase_uncorrected",(N,WINDOW_FRAMES))
            chosen_co=ds(radar,"selected_phase_corrected",(N,WINDOW_FRAMES))
            center_ds=ds(radar,"iq_circle_center",(N,R,2))
            radius_ds=ds(radar,"iq_circle_radius",(N,R))
            cond_ds=ds(radar,"circle_fit_condition",(N,R))
            resid_ds=ds(radar,"circle_fit_radial_error",(N,R))
            coverage_ds=ds(radar,"circle_fit_coverage_deg",(N,R))
            fitvalid_ds=ds(radar,"circle_fit_valid",(N,R),np.bool_)
            applied_ds=ds(radar,"correction_applied",(N,R),np.bool_)

            spec_un_ds=ds(model,"vibration_spectrum_uncorrected",(N,R,F))
            spec_co_ds=ds(model,"vibration_spectrum_corrected",(N,R,F))
            model.create_dataset("frequency_hz",data=frequencies.astype(np.float32))
            vibration_score_ds=ds(model,"vibration_energy_score",(N,R))
            mti_score_ds=ds(model,"mti_energy_score",(N,R))
            hr_un_ds=ds(model,"heart_rate_uncorrected_bpm",(N,))
            hr_co_ds=ds(model,"heart_rate_corrected_bpm",(N,))
            peak_un_ds=ds(model,"peak_frequency_uncorrected_hz",(N,))
            peak_co_ds=ds(model,"peak_frequency_corrected_hz",(N,))
            valid_ds=ds(model,"valid",(N,),np.bool_)
            chosen_fit_ds=ds(model,"selected_circle_fit_valid",(N,),np.bool_)

            block_indices=np.arange(N,dtype=np.int32)
            model.create_dataset("source_block_index",data=block_indices)
            model.create_dataset("source_raw_frame_start",data=audit['start_frame']+STRIDE_FRAMES*block_indices)
            model.create_dataset("source_raw_frame_end",data=audit['start_frame']+STRIDE_FRAMES*block_indices+WINDOW_FRAMES)
            model.create_dataset("window_start_s",data=18.0*block_indices)
            model.create_dataset("window_end_s",data=18.0*block_indices+36.0)
            model.create_dataset("window_start_utc",data=np.asarray([
                iso(audit['start_dt']+timedelta(seconds=18*int(i))) for i in block_indices
            ],dtype=object),dtype=utf8)
            model.create_dataset("window_end_utc",data=np.asarray([
                iso(audit['start_dt']+timedelta(seconds=18*int(i)+36)) for i in block_indices
            ],dtype=object),dtype=utf8)

            iterator=iter_range_blocks(audit['files'],audit['counts'],
                                       start_frame=audit['start_frame'],
                                       frames_to_keep=audit['retained']*SOURCE_BLOCK_FRAMES,
                                       loops_per_tx=loops_per_tx,
                                       tx=tx,rx=rx,chirp_loop=chirp_loop,
                                       fft_size=fft_size,range_bins=range_bins)
            processed=0
            for block_idx,cube in enumerate(iterator):
                # cube [400,R] complex, HANN range FFT, no chirp/angle/Doppler FFT.
                iq_ds[block_idx,:,:,0]=cube.real
                iq_ds[block_idx,:,:,1]=cube.imag
                un_ph=np.zeros((WINDOW_FRAMES,R),np.float32)
                co_ph=np.zeros((WINDOW_FRAMES,R),np.float32)
                centers=np.full((R,2),np.nan,np.float32)
                radii=np.full(R,np.nan,np.float32)
                conds=np.full(R,np.inf,np.float32)
                resid=np.full(R,np.inf,np.float32)
                coverage=np.zeros(R,np.float32)
                fit_valid=np.zeros(R,np.bool_)
                spectra_un=np.zeros((R,F),np.float32)
                spectra_co=np.zeros((R,F),np.float32)
                vib_power=np.zeros(R,np.float32)

                mti_power=np.mean(np.abs(cube-cube.mean(axis=0,keepdims=True))**2,
                                  axis=0).astype(np.float32)
                for col in range(R):
                    z=cube[:,col]
                    # Protect against trivial almost-zero complex values.
                    if not np.all(np.isfinite(z)) or np.mean(np.abs(z)) <= 1e-8:
                        continue
                    p0=np.unwrap(np.angle(z))
                    corr,centre,radius,cond,rel_err,arc,ok=alizadeh_circle_fit(z)
                    p1=np.unwrap(np.angle(corr))
                    un_ph[:,col]=p0
                    co_ph[:,col]=p1
                    centers[col]=centre
                    radii[col]=radius
                    conds[col]=cond
                    resid[col]=rel_err
                    coverage[col]=arc
                    fit_valid[col]=ok
                    spectra_un[col]=vibration_fft(p0,window=taper)
                    spectra_co[col]=vibration_fft(p1,window=taper)
                    # Physiological-band vibration energy, computed without labels.
                    vib_power[col]=np.sum(spectra_un[col,band_mask].astype(np.float64)**2)

                scores=(vib_power if range_method=="vibration-energy" else mti_power)
                chosen=int(np.argmax(scores))
                # Valid means enough radar evidence for a spectral peak, NOT
                # that this window has a correct physiological heart rate.
                usable=bool(np.mean(np.abs(cube[:,chosen]))>1e-8
                            and np.std(un_ph[:,chosen])>1e-6
                            and np.any(spectra_un[chosen]>0)
                            and scores[chosen]>1e-12)
                selected_range[block_idx]=range_bins[chosen]
                un_ph_ds[block_idx]=un_ph
                co_ph_ds[block_idx]=co_ph
                chosen_un[block_idx]=un_ph[:,chosen]
                chosen_co[block_idx]=co_ph[:,chosen]
                center_ds[block_idx]=centers
                radius_ds[block_idx]=radii
                cond_ds[block_idx]=conds
                resid_ds[block_idx]=resid
                coverage_ds[block_idx]=coverage
                fitvalid_ds[block_idx]=fit_valid
                applied_ds[block_idx]=fit_valid
                spec_un_ds[block_idx]=spectra_un
                spec_co_ds[block_idx]=spectra_co
                vibration_score_ds[block_idx]=vib_power
                mti_score_ds[block_idx]=mti_power
                valid_ds[block_idx]=usable
                chosen_fit_ds[block_idx]=fit_valid[chosen]
                if usable:
                    pu=gaussian_peak_frequency(spectra_un[chosen],fs,heart_low_hz,heart_high_hz)
                    pc=gaussian_peak_frequency(spectra_co[chosen],fs,heart_low_hz,heart_high_hz)
                else:
                    pu=pc=float("nan")
                peak_un_ds[block_idx]=pu
                peak_co_ds[block_idx]=pc
                hr_un_ds[block_idx]=pu*60.0
                hr_co_ds[block_idx]=pc*60.0
                processed+=1
                if processed%25==0 or processed==N:
                    print(f"    {processed}/{N} aligned windows exported")
            if processed!=N:
                raise RuntimeError(f"Exported {processed} windows; source has {N}")
            f.flush()
        os.replace(temp,target)
    except BaseException:
        if temp.exists():
            temp.unlink()
        raise
    print(f"Saved: {target} ({N} × 36-second windows; {R} candidate ranges)")
    return target


def discover_sessions(root: Path):
    if not root.is_dir():
        raise FileNotFoundError(f"ICR-DS root directory not found: {root}")
    subjects=[]
    for path in root.iterdir():
        m=SUBJECT_RE.fullmatch(path.name)
        if path.is_dir() and m:
            subjects.append((int(m.group(1)),path))
    for subject,folder in sorted(subjects,key=lambda x:(x[0],x[1].name)):
        processed=folder/"processed"
        found=[]
        if processed.is_dir():
            for p in processed.iterdir():
                m=SESSION_RE.fullmatch(p.name)
                if p.is_file() and m and int(m.group(1))==subject:
                    found.append(p)
        if len(found)>1:
            raise ValueError(f"Ambiguous matching session HDF5s in {processed}: {found}")
        old=found[0] if found else None
        out=processed/(old.name.replace("_session.h5","_alizadeh.h5")
                       if old else f"s{subject:03d}_alizadeh.h5")
        yield subject,old,folder/"raw"/"radar",out


def batch_export(root: Path) -> dict:
    """Export every subject found under the ICR-DS root; never overwrite."""
    summary = dict(done=0, existing=0, missing=0, errors=0)
    found_any = False
    for subject, source_h5, raw_dir, output_h5 in discover_sessions(root):
        found_any = True
        label = f"sub-{subject:03d}"
        if source_h5 is None or not raw_dir.is_dir():
            print(f"[SKIP missing] {label}: aligned session HDF5 or raw radar folder missing")
            summary["missing"] += 1
            continue
        if output_h5.exists():
            print(f"[SKIP existing] {label}: {output_h5.name}")
            summary["existing"] += 1
            continue
        print(f"\n[{label}] Exporting {output_h5.name}")
        try:
            export_alizadeh(
                source_h5, raw_dir, output_h5,
                tx=TX_INDEX, rx=RX_INDEX, chirp_loop=CHIRP_LOOP,
                loops_per_tx=LOOPS_PER_TX, fft_size=FFT_SIZE,
                range_start=RANGE_START, range_stop=RANGE_STOP,
                frame_period_s=FRAME_PERIOD_S, range_method=RANGE_METHOD,
                range_low_hz=RANGE_LOW_HZ, range_high_hz=RANGE_HIGH_HZ,
                heart_low_hz=HEART_LOW_HZ, heart_high_hz=HEART_HIGH_HZ,
                vibration_hann=VIBRATION_HANN,
            )
            summary["done"] += 1
        except Exception as exc:
            print(f"[ERROR] {label}: {type(exc).__name__}: {exc}")
            summary["errors"] += 1

    if not found_any:
        print(f"No sub-XXX subject folders found under {root}")
    print("\nBatch summary: " + ", ".join(
        f"{key}={value}" for key, value in summary.items()))
    return summary


def main() -> None:
    summary = batch_export(DATA_ROOT)
    if summary["errors"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
